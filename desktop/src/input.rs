fn utf8_offset(text: &str, offset: usize) -> usize {
    let mut bytes = 0;
    let mut units = 0;
    for character in text.chars() {
        if units >= offset {
            break;
        }
        units += character.len_utf16();
        bytes += character.len_utf8();
    }
    bytes
}

fn utf16_offset(text: &str, offset: usize) -> usize {
    let mut bytes = 0;
    let mut units = 0;
    for character in text.chars() {
        if bytes >= offset {
            break;
        }
        bytes += character.len_utf8();
        units += character.len_utf16();
    }
    units
}

fn horizontal_offset(cursor: Pixels, line: Pixels, width: Pixels, previous: Pixels) -> Pixels {
    let visible = (width - px(2.)).max(px(0.));
    let offset = previous.min(cursor).max(cursor - visible);
    offset.clamp(px(0.), (line - visible).max(px(0.)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn native_offsets_preserve_unicode_scalar_boundaries_and_clamp() {
        let text = "e🙂漢தமிழ்";
        for (byte_offset, _) in text.char_indices() {
            let utf16 = utf16_offset(text, byte_offset);
            assert_eq!(utf8_offset(text, utf16), byte_offset);
        }
        assert_eq!(utf8_offset(text, usize::MAX), text.len());
        assert_eq!(utf16_offset(text, usize::MAX), text.encode_utf16().count());
        assert_eq!(utf8_offset(text, 2), 5);
    }

    #[test]
    fn long_field_keeps_caret_visible_and_returns_to_the_start() {
        assert_eq!(
            horizontal_offset(px(10.), px(500.), px(100.), px(0.)),
            px(0.)
        );
        assert_eq!(
            horizontal_offset(px(400.), px(500.), px(100.), px(0.)),
            px(302.)
        );
        assert_eq!(
            horizontal_offset(px(20.), px(500.), px(100.), px(302.)),
            px(20.)
        );
        assert_eq!(horizontal_offset(px(0.), px(0.), px(100.), px(20.)), px(0.));
    }
}
